#!/usr/bin/env python3
"""Builds Shugyo/Harae content from study/lessons and study/scenarios.

Run from mitamaos/firmware:  python3 tools/mkstudy.py
  writes src/study/builtin_content.h  (the small built-in fallback set)
  and    test/study_all_content.h     (every file, for the host test)
With --check it only reports whether both are up to date (CI uses it).
With --pack DIR it also writes DIR/study.pack and DIR/study.txt: the full
set that Molt downloads to the SD card (/MitamaOS/study/).

Built-in fallback: lessons whose file starts with "t" (Foundations) and
the s02 practice drill (its Wards are all Foundations). Everything else (the faction
arcs and their drills) lives on the SD card and arrives through Molt.
"""
import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "study" / "builtin_content.h"
ALL = ROOT / "test" / "study_all_content.h"
# The lesson engine version comes from study::kEngine in src/study/lesson.h.
ENGINE = int(re.search(r"constexpr int kEngine = (\d+);", (ROOT / "src" / "study" / "lesson.h").read_text()).group(1))
BUILTIN_PREFIX = {"lessons": "t", "scenarios": "s02"}


def files(kind):
    return sorted((ROOT / "study" / kind).glob("*.lua"))


def header(only_builtin, prefix):
    parts = [
        "// Generated by tools/mkstudy.py from study/ - do not edit by hand.",
        "#pragma once",
        "",
        "namespace study {",
        "",
        "#ifndef STUDY_BUILTIN_FILE",
        "#define STUDY_BUILTIN_FILE",
        "struct BuiltinFile { const char* name; const char* source; };",
        "#endif",
        "",
    ]
    for kind in ("lessons", "scenarios"):
        chosen = [f for f in files(kind) if not only_builtin or f.name.startswith(BUILTIN_PREFIX[kind])]
        parts.append(f"static const BuiltinFile {prefix}_{kind}[] = {{")
        for f in chosen:
            text = f.read_text(encoding="utf-8")
            if ")LUA\"" in text:
                sys.exit(f"{f.name}: contains the raw-string delimiter )LUA\"")
            parts.append(f'  {{ "{f.name}", R"LUA({text})LUA" }},')
        if not chosen:
            parts.append('  { "", "" },')
        parts.append("};")
        parts.append(f"static constexpr int {prefix}_{kind}_count = {len(chosen)};")
        parts.append("")
    parts.append("}  // namespace study")
    return "\n".join(parts) + "\n"


def pack():
    """Text pack: a header line, then for each file "F <path> <bytes>\\n<bytes>\\n", then "E\\n"."""
    body = b""
    for kind in ("lessons", "scenarios"):
        for f in files(kind):
            data = f.read_bytes()
            body += f"F {kind}/{f.name} {len(data)}\n".encode() + data + b"\n"
    version = hashlib.sha1(body).hexdigest()[:10]
    return f"MITAMA-STUDY 1 {version} {ENGINE}\n".encode() + body + b"E\n", version


def main():
    builtin, every = header(True, "kBuiltin"), header(False, "kAll")
    if "--check" in sys.argv:
        for path, text in ((OUT, builtin), (ALL, every)):
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                sys.exit(f"{path.relative_to(ROOT)} is out of date: run python3 tools/mkstudy.py")
        print("study headers are up to date")
    else:
        OUT.write_text(builtin, encoding="utf-8")
        ALL.write_text(every, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)} and {ALL.relative_to(ROOT)}")
    if "--pack" in sys.argv:
        out = pathlib.Path(sys.argv[sys.argv.index("--pack") + 1])
        out.mkdir(parents=True, exist_ok=True)
        data, version = pack()
        (out / "study.pack").write_bytes(data)
        (out / "study.txt").write_text(f"{version} {ENGINE} {len(data)}\n", encoding="utf-8")
        print(f"wrote {out}/study.pack ({len(data)} bytes, version {version}, engine {ENGINE})")


if __name__ == "__main__":
    main()
